// Writes docs/whatsapp-templates-for-meta.md and docs/email-samples/*.html from the seeded templates, so they can't drift.
// Memory store only: nothing is sent and no database is touched.
//   node tools/gen-message-docs.mjs
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { createCRM, createMemoryStore } = require("../lib/core.js");
const { renderEmail } = require("../lib/email-layout.js");
const store = createMemoryStore(); store.transaction = fn => fn();
const crm = createCRM({ store, hashPassword: p => p, verifyPassword: () => true, hashToken: t => t, random: n => new Uint8Array(n), onQueue: () => {} });
crm.ensureDefaults();
const admin = { id: "doc", role: "admin" }, s = crm.getSettings(), sample = crm.previewTemplate(admin, { body: "" });
const preview = t => crm.previewTemplate(admin, t);
const valueOf = k => { const b = crm.previewTemplate(admin, { body: `{{${k}}}` }).body; return b || k; };

// WhatsApp: variables in wa_params become {{1}}, {{2}}…; anything else is fixed text in the approved template
const rows = store.all("templates").filter(t => t.channel === "whatsapp").sort((a, b) => a.id.localeCompare(b.id));
const toMeta = t => { const ps = t.wa_params || [], fixed = []; const body = t.body.replace(/\{\{\s*([a-z_]+)\s*\}\}/g, (m, k) => { const i = ps.indexOf(k); if (i >= 0) return `{{${i + 1}}}`; fixed.push(k); return valueOf(k); }); return { body, fixed: [...new Set(fixed)] }; };
const metaName = t => t.wa_template_name || "absel_" + t.id.replace(/^tpl_wa_/, "");
let md = `# WhatsApp templates to submit to Meta

Generated by \`node tools/gen-message-docs.mjs\` from the seeded templates. Submit each one in Meta Business Manager, then put the approved name in **Templates → the template → Approved Meta template name**. A new template sends only once that name is filled in; until then its automation logs "WhatsApp template not approved yet".

- **UTILITY**: account, payment and KYC messages. **MARKETING**: offers and re-engagement.
- Language: \`en\` for all of them.
- The header, body, footer and buttons in the back office must match what Meta approved exactly, or Meta refuses the send and the error shows on the message.
- Templates marked *already in use* have an existing name. Check whether Meta already approved them, and that the wording below matches.
- No template contains a password, and none may.

`;
for (const t of rows) {
  const m = toMeta(t);
  md += `## ${t.name}\n\n| | |\n|---|---|\n| **Name** | \`${metaName(t)}\`${t.wa_template_name ? " *(already in use)*" : ""} |\n| **Category** | ${t.category === "marketing" ? "MARKETING" : "UTILITY"} |\n| **Language** | ${t.wa_language || "en"} |\n| **Header** | ${t.wa_header_type && t.wa_header_type !== "none" ? t.wa_header_text || t.wa_header_image_url : "None"} |\n| **Footer** | ${t.wa_footer_text || "None"} |\n| **Buttons** | ${(t.wa_buttons || []).map(b => b.text).join(", ") || "None"} |\n\n**Body**\n\n> ${m.body}\n\n`;
  if ((t.wa_params || []).length) md += `**Sample values**\n\n${t.wa_params.map((k, i) => `- \`{{${i + 1}}}\` (${k}): ${valueOf(k)}`).join("\n")}\n\n`;
  if (m.fixed.length) md += `**Note:** ${m.fixed.join(", ")} is written as fixed text above, because this template doesn't send it as a value.\n\n`;
}
fs.writeFileSync("docs/whatsapp-templates-for-meta.md", md);

fs.mkdirSync("docs/email-samples", { recursive: true });
for (const [file, id] of [["welcome", "tpl_welcome_email"], ["demo-ready", "tpl_demo_ready"], ["deposit-received", "tpl_portal_deposit"]]) {
  const t = store.get("templates", id), r = renderEmail(preview(t), s);
  fs.writeFileSync(`docs/email-samples/${file}.html`, r.html); fs.writeFileSync(`docs/email-samples/${file}.txt`, r.text);
}
console.log(`✔ ${rows.length} WhatsApp templates and 3 sample emails written (${Object.keys(sample).length} fields)`);
